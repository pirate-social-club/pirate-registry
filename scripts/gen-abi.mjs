// Writes viem-typed ABIs from the solc build in out/. Run after `forge build`.
import { readFileSync, writeFileSync } from 'node:fs';

const load = (path) => JSON.parse(readFileSync(new URL(`../out/${path}`, import.meta.url), 'utf8')).abi;
const registry = load('SLDRegistry.sol/SLDRegistry.json');
const factory = load('RegistryFactory.sol/RegistryFactory.json');

const body = `// Generated by scripts/gen-abi.mjs from the solc build. Do not edit.
export const registryAbi = ${JSON.stringify(registry, null, 2)} as const;

export const factoryAbi = ${JSON.stringify(factory, null, 2)} as const;
`;
writeFileSync(new URL('../packages/resolver/src/abi.ts', import.meta.url), body);
console.log(`registryAbi: ${registry.length} entries, factoryAbi: ${factory.length} entries`);
